// ─── 1. PdfWriter — core PDF generation ──────────────────────────────────────

describe("PdfWriter — core functionality", () => {
  test("build() produces a Buffer", () => {
    const pdf = new PdfWriter();
    pdf.addTitle("Test Document");
    pdf.addParagraph("Hello, world.");
    const buffer = pdf.build();
    assert.ok(Buffer.isBuffer(buffer), "Expected a Buffer");
  });

  test("PDF starts with %PDF-1.4 header", () => {
    const pdf = new PdfWriter();
    pdf.addParagraph("Test content");
    const buffer = pdf.build();
    const header = buffer.toString("binary", 0, 8);
    assert.ok(header.startsWith("%PDF-1.4"), `Expected PDF header, got: ${header}`);
  });

  test("PDF ends with %%EOF", () => {
    const pdf = new PdfWriter();
    pdf.addParagraph("Test content");
    const buffer = pdf.build();
    const tail = buffer.toString("binary", buffer.length - 10).trim();
    assert.ok(tail.endsWith("%%EOF"), `Expected %%EOF trailer, got: ${tail}`);
  });

  test("PDF contains Font reference to Helvetica", () => {
    const pdf = new PdfWriter();
    pdf.addParagraph("Font test");
    const str = pdf.build().toString("binary");
    assert.ok(str.includes("/Helvetica"), "Expected Helvetica font reference");
  });

  test("PDF contains Helvetica-Bold for bold text", () => {
    const pdf = new PdfWriter();
    pdf.addBold("Bold text");
    const str = pdf.build().toString("binary");
    assert.ok(str.includes("/Helvetica-Bold"), "Expected Helvetica-Bold reference");
  });

  test("addTitle places text in the output", () => {
    const pdf = new PdfWriter();
    pdf.addTitle("My Document Title");
    const str = pdf.build().toString("binary");
    assert.ok(str.includes("My Document Title"), "Expected title in PDF stream");
  });

  test("addParagraph includes paragraph text", () => {
    const pdf = new PdfWriter();
    pdf.addParagraph("This is paragraph text about consumer rights.");
    const str = pdf.build().toString("binary");
    assert.ok(str.includes("consumer rights"), "Expected paragraph text in PDF");
  });

  test("addRule produces stroke command 'S' in stream", () => {
    const pdf = new PdfWriter();
    pdf.addRule();
    const str = pdf.build().toString("binary");
    assert.ok(str.includes(" l S"), "Expected line stroke command");
  });

  test("produces multiple pages for very long content", () => {
    const pdf = new PdfWriter();
    // Add enough text to force multiple pages (~70 lines per page)
    for (let i = 0; i < 120; i++) {
      pdf.addParagraph(`Line ${i + 1}: This is a paragraph that should occupy one line in the PDF output.`);
    }
    const str = pdf.build().toString("binary");
    // Count /Type /Page occurrences (each page object has one)
    const pageCount = (str.match(/\/Type \/Page\b/g) || []).length;
    assert.ok(pageCount >= 2, `Expected ≥2 pages, found ${pageCount}`);
  });

  test("escapes parentheses in text", () => {
    const pdf = new PdfWriter();
    pdf.addParagraph("Section 35(1)(a) applies here.");
    const str = pdf.build().toString("binary");
    assert.ok(str.includes("35\\(1\\)\\(a\\)"), "Expected escaped parentheses");
  });

  test("empty writer produces a valid single-page PDF", () => {
    const pdf = new PdfWriter();
    const buffer = pdf.build();
    // Should not throw and should produce a minimal PDF
    assert.ok(buffer.length > 100, "Expected non-trivial PDF output");
  });
});

// ─── 2. PDF Generator — structured document rendering ─────────────────────────

describe("generateDocumentPdf — structured rendering", () => {
  test("produces a Buffer from a mock document", () => {
    const buffer = generateDocumentPdf(makeMockDocument());
    assert.ok(Buffer.isBuffer(buffer));
    assert.ok(buffer.length > 500);
  });

  test("includes the document title", () => {
    const buffer = generateDocumentPdf(makeMockDocument({ title: "Test Title XYZ" }));
    const str = buffer.toString("binary");
    assert.ok(str.includes("Test Title XYZ"));
  });

  test("includes DRAFT banner for draft status", () => {
    const buffer = generateDocumentPdf(makeMockDocument({ status: "draft" }));
    const str = buffer.toString("binary");
    assert.ok(str.includes("DRAFT"));
  });

  test("does NOT include DRAFT banner for confirmed status", () => {
    const buffer = generateDocumentPdf(makeMockDocument({ status: "confirmed" }));
    const str = buffer.toString("binary");
    assert.ok(!str.includes("NOT YET REVIEWED"));
  });

  test("includes STATEMENT OF FACTS section", () => {
    const buffer = generateDocumentPdf(makeMockDocument());
    const str = buffer.toString("binary");
    assert.ok(str.includes("STATEMENT OF FACTS"));
  });

  test("includes LEGAL GROUNDS section", () => {
    const buffer = generateDocumentPdf(makeMockDocument());
    const str = buffer.toString("binary");
    assert.ok(str.includes("LEGAL GROUNDS"));
  });

  test("includes disclaimer text", () => {
    const buffer = generateDocumentPdf(makeMockDocument());
    const str = buffer.toString("binary");
    assert.ok(str.includes("DISCLAIMER"));
  });

  test("includes placeholder summary section when placeholders exist", () => {
    const buffer = generateDocumentPdf(makeMockDocument());
    const str = buffer.toString("binary");
    assert.ok(str.includes("INFORMATION STILL REQUIRED"));
  });

  test("does NOT include placeholder section when none exist", () => {
    const buffer = generateDocumentPdf(makeMockDocument({ placeholders: [] }));
    const str = buffer.toString("binary");
    assert.ok(!str.includes("INFORMATION STILL REQUIRED"));
  });

  test("includes citation references when present", () => {
    const buffer = generateDocumentPdf(makeMockDocument());
    const str = buffer.toString("binary");
    assert.ok(str.includes("LEGAL SOURCES CITED"));
    assert.ok(str.includes("Consumer Protection Act"));
  });

  test("renders a document with empty sections without crashing", () => {
    const doc = makeMockDocument({
      sections: {
        header: "",
        reference: "",
        date: "",
        from: "",
        to: "",
        salutation: "",
        factStatement: "Some facts.",
        legalGrounds: "Some grounds.",
        prayer: "",
        closing: "",
      },
      citations: [],
      placeholders: [],
    });
    const buffer = generateDocumentPdf(doc);
    assert.ok(Buffer.isBuffer(buffer));
    assert.ok(buffer.length > 100);
  });
});

// ─── 3. Zod validators ───────────────────────────────────────────────────────

describe("generateDocumentSchema — request body validation", () => {
  test("accepts all five document types", () => {
    const types = [
      "consumer_complaint",
      "refund_request",
      "legal_notice",
      "legal_notice_reply",
      "grievance_application",
    ];
    for (const t of types) {
      const result = generateDocumentSchema.safeParse({ documentType: t });
      assert.equal(result.success, true, `Expected success for ${t}`);
    }
  });

  test("rejects an unknown document type", () => {
    const result = generateDocumentSchema.safeParse({ documentType: "writ_petition" });
    assert.equal(result.success, false);
  });

  test("accepts caseId with valid ObjectId format", () => {
    const result = generateDocumentSchema.safeParse({
      documentType: "legal_notice",
      caseId: "507f1f77bcf86cd799439011",
    });
    assert.equal(result.success, true);
  });

  test("rejects invalid caseId format", () => {
    const result = generateDocumentSchema.safeParse({
      documentType: "legal_notice",
      caseId: "not-valid",
    });
    assert.equal(result.success, false);
  });

  test("accepts inline caseData with all fields", () => {
    const result = generateDocumentSchema.safeParse({
      documentType: "consumer_complaint",
      caseData: {
        category: "Consumer Dispute",
        subCategory: "Defective Product",
        jurisdiction: { state: "Karnataka", city: "Bengaluru" },
        parties: ["Rahul", "XYZ Corp"],
        events: [{ description: "Bought laptop", date: "2024-01-15" }],
        financialDetails: { amount: 55000, currency: "INR" },
        evidence: ["Invoice"],
        userClaims: ["Product was defective"],
        urgency: "medium",
      },
    });
    assert.equal(result.success, true);
  });

  test("accepts request with only documentType (no case data)", () => {
    const result = generateDocumentSchema.safeParse({
      documentType: "refund_request",
    });
    assert.equal(result.success, true);
  });

  test("accepts additionalInstructions", () => {
    const result = generateDocumentSchema.safeParse({
      documentType: "legal_notice",
      additionalInstructions: "Use a formal tone. Mention 30-day deadline.",
    });
    assert.equal(result.success, true);
  });

  test("rejects additionalInstructions longer than 2000 chars", () => {
    const result = generateDocumentSchema.safeParse({
      documentType: "legal_notice",
      additionalInstructions: "x".repeat(2001),
    });
    assert.equal(result.success, false);
  });
});

