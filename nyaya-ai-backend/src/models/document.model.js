import mongoose from "mongoose";

// ─── Sub-schemas ──────────────────────────────────────────────────────────────

const CitationReferenceSchema = new mongoose.Schema(
  {
    citationKey: { type: String, required: true },
    actName: { type: String, required: true },
    sectionNumber: { type: String, default: null },
    sourceType: { type: String, default: null },
    sourceUrl: { type: String, default: null },
    lastVerifiedDate: { type: String, default: null },
  },
  { _id: false }
);

const DocumentVersionSchema = new mongoose.Schema(
  {
    versionNumber: { type: Number, required: true },
    content: { type: String, required: true },
    sections: { type: mongoose.Schema.Types.Mixed, default: {} },
    generatedAt: { type: Date, default: Date.now },
    changes: { type: String, default: null },
  },
  { _id: false }
);

// ─── Main LegalDocument Schema ───────────────────────────────────────────────

const LegalDocumentSchema = new mongoose.Schema(
  {
    // ── Type / classification ─────────────────────────────────────────────
    documentType: {
      type: String,
      enum: [
        "consumer_complaint",
        "refund_request",
        "legal_notice",
        "legal_notice_reply",
        "grievance_application",
      ],
      required: true,
    },

    /** Human-readable document title auto-generated from type + case info */
    title: { type: String, required: true },

    // ── Status workflow ───────────────────────────────────────────────────
    /**
     * draft     → user has not yet confirmed
     * confirmed → user reviewed and approved
     * final     → PDF generated (downloadable)
     */
    status: {
      type: String,
      enum: ["draft", "confirmed", "final"],
      default: "draft",
    },

    // ── Content ───────────────────────────────────────────────────────────
    /** Current formatted document body (plain text with markers) */
    content: { type: String, required: true },

    /**
     * Structured sections of the document.
     * Keys vary by document type (e.g. "header", "parties", "factStatement",
     * "prayer", "signature") but are always present.
     */
    sections: { type: mongoose.Schema.Types.Mixed, default: {} },

    // ── Source traceability ────────────────────────────────────────────────
    /** Linked case ObjectId (from the case extraction engine), optional */
    caseId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "LegalCase",
      default: null,
    },

    /** Case data snapshot used for generation (prevents drift) */
    caseSnapshot: { type: mongoose.Schema.Types.Mixed, default: null },

    /** Verified legal citations included in this document */
    citations: { type: [CitationReferenceSchema], default: [] },

    /** Fields marked as placeholders — user must fill before confirming */
    placeholders: { type: [String], default: [] },

    // ── Versioning ────────────────────────────────────────────────────────
    currentVersion: { type: Number, default: 1 },
    versions: { type: [DocumentVersionSchema], default: [] },

    // ── PDF ───────────────────────────────────────────────────────────────
    /** Binary PDF stored as Buffer (generated on confirm/finalize) */
    pdfBuffer: { type: Buffer, default: null, select: false },
    pdfGeneratedAt: { type: Date, default: null },

    // ── Safety ────────────────────────────────────────────────────────────
    /**
     * Prominent disclaimer embedded in every document.
     * Immutable after creation.
     */
    disclaimer: {
      type: String,
      default:
        "DISCLAIMER: This document has been generated by NyayaAI, an artificial intelligence " +
        "system. It has NOT been reviewed by a qualified legal professional. This is a " +
        "draft for informational purposes only. Consult a licensed advocate before relying " +
        "on or submitting this document. NyayaAI does not provide legal advice. " +
        "This document does not establish an attorney-client relationship.",
    },

    /** Raw Gemini output stored for audit */
    rawGeminiResponse: { type: mongoose.Schema.Types.Mixed, default: null, select: false },
  },
  {
    timestamps: true,
    collection: "legal_documents",
  }
);

LegalDocumentSchema.index({ documentType: 1, status: 1 });
LegalDocumentSchema.index({ caseId: 1 });
LegalDocumentSchema.index({ createdAt: -1 });

export const LegalDocument = mongoose.model("LegalDocument", LegalDocumentSchema);

