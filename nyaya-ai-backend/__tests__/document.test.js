// ─── 5. Placeholder detection ─────────────────────────────────────────────────

describe("Placeholder patterns", () => {
  test("[PLACEHOLDER: ...] markers are detectable in document content", () => {
    const content = makeMockDocument().sections.from;
    const placeholders = content.match(/\[PLACEHOLDER: [^\]]+\]/g);
    assert.ok(placeholders, "Expected placeholder patterns");
    assert.ok(placeholders.length >= 1);
  });

  test("placeholder text can be extracted from the marker", () => {
    const marker = "[PLACEHOLDER: Complainant's full address]";
    const match = marker.match(/\[PLACEHOLDER: (.+?)\]/);
    assert.equal(match[1], "Complainant's full address");
  });

  test("replacement removes the marker from content", () => {
    let content = "From: [PLACEHOLDER: Complainant's address]\nCity: Bengaluru";
    content = content.replaceAll(
      "[PLACEHOLDER: Complainant's address]",
      "123 MG Road, Bengaluru"
    );
    assert.ok(!content.includes("[PLACEHOLDER:"));
    assert.ok(content.includes("123 MG Road"));
  });
});

// ─── 6. Workflow constraints (pure logic checks) ─────────────────────────────

describe("Document status workflow", () => {
  test("valid statuses are draft → confirmed → final", () => {
    const validStatuses = ["draft", "confirmed", "final"];
    for (const s of validStatuses) {
      assert.ok(typeof s === "string");
    }
    // Verify the workflow ordering makes sense
    assert.notEqual(
      validStatuses.indexOf("draft"),
      validStatuses.indexOf("final")
    );
    assert.ok(
      validStatuses.indexOf("draft") < validStatuses.indexOf("confirmed"),
      "draft should come before confirmed"
    );
    assert.ok(
      validStatuses.indexOf("confirmed") < validStatuses.indexOf("final"),
      "confirmed should come before final"
    );
  });
});

