import { PdfWriter } from "./pdfWriter.service.js";
import { DOCUMENT_TYPE_LABELS } from "./drafting.service.js";

/**
 * Generates a formatted PDF Buffer from a structured legal document.
 *
 * @param {object} doc  LegalDocument Mongoose document (or plain object with same shape)
 * @returns {Buffer}    Valid PDF 1.4 buffer
 */
export function generateDocumentPdf(doc) {
  const pdf = new PdfWriter();
  const sections = doc.sections || {};
  const typeLabel = DOCUMENT_TYPE_LABELS[doc.documentType] ?? doc.documentType;

  // ── Title ───────────────────────────────────────────────────────────────
  pdf.addTitle(doc.title || typeLabel);
  pdf.addSpace(1);

  // ── Status banner ──────────────────────────────────────────────────────
  if (doc.status === "draft") {
    pdf.addBold("*** DRAFT — NOT YET REVIEWED OR CONFIRMED BY THE USER ***");
    pdf.addSpace(1);
  }

  // ── Header (forum / authority) ─────────────────────────────────────────
  if (sections.header) {
    pdf.addBold(sections.header);
    pdf.addSpace(1);
  }

  // ── Reference / Subject ─────────────────────────────────────────────────
  if (sections.reference) {
    pdf.addBold(`Subject: ${sections.reference}`);
    pdf.addSpace(1);
  }

  // ── Date ────────────────────────────────────────────────────────────────
  if (sections.date) {
    pdf.addRightAligned(sections.date);
  }

  // ── From ────────────────────────────────────────────────────────────────
  if (sections.from) {
    pdf.addHeader("FROM:");
    pdf.addParagraph(sections.from);
  }

  // ── To ──────────────────────────────────────────────────────────────────
  if (sections.to) {
    pdf.addHeader("TO:");
    pdf.addParagraph(sections.to);
  }

  // ── Salutation ──────────────────────────────────────────────────────────
  if (sections.salutation) {
    pdf.addSpace(1);
    pdf.addParagraph(sections.salutation);
  }

  // ── Statement of Facts ──────────────────────────────────────────────────
  pdf.addRule();
  pdf.addHeader("STATEMENT OF FACTS");
  pdf.addParagraph("(Based on information provided by the user)");
  pdf.addSpace(1);
  _addMultiParagraph(pdf, sections.factStatement);

  // ── Legal Grounds ───────────────────────────────────────────────────────
  pdf.addRule();
  pdf.addHeader("LEGAL GROUNDS");
  pdf.addParagraph("(Based on retrieved and verified legal provisions)");
  pdf.addSpace(1);
  _addMultiParagraph(pdf, sections.legalGrounds);

  // ── Prayer / Relief Sought ──────────────────────────────────────────────
  if (sections.prayer) {
    pdf.addRule();
    pdf.addHeader("RELIEF SOUGHT / PRAYER");
    _addMultiParagraph(pdf, sections.prayer);
  }

  // ── Annexures ───────────────────────────────────────────────────────────
  if (sections.annexures) {
    pdf.addRule();
    pdf.addHeader("ANNEXURES");
    _addMultiParagraph(pdf, sections.annexures);
  }

  // ── Closing / Signature ─────────────────────────────────────────────────
  if (sections.closing) {
    pdf.addSpace(2);
    _addMultiParagraph(pdf, sections.closing);
  }

  // ── Citations ───────────────────────────────────────────────────────────
  if (doc.citations?.length > 0) {
    pdf.addSpace(2);
    pdf.addRule();
    pdf.addHeader("LEGAL SOURCES CITED");
    for (const c of doc.citations) {
      const line = `${c.citationKey} — ${c.actName}${c.sectionNumber ? `, Section ${c.sectionNumber}` : ""}`;
      pdf.addParagraph(line);
      if (c.sourceUrl) {
        pdf.addParagraph(`  Source: ${c.sourceUrl}`);
      }
    }
  }

  // ── Placeholders summary ───────────────────────────────────────────────
  if (doc.placeholders?.length > 0) {
    pdf.addSpace(1);
    pdf.addRule();
    pdf.addHeader("INFORMATION STILL REQUIRED");
    pdf.addParagraph(
      "The following placeholders must be filled in before this document can be used:"
    );
    pdf.addSpace(1);
    for (let i = 0; i < doc.placeholders.length; i++) {
      pdf.addParagraph(`${i + 1}. ${doc.placeholders[i]}`);
    }
  }

  // ── Disclaimer (always last) ───────────────────────────────────────────
  pdf.addSpace(2);
  pdf.addDisclaimer(
    doc.disclaimer ||
      "DISCLAIMER: This document has been generated by NyayaAI, an artificial intelligence " +
        "system. It has NOT been reviewed by a qualified legal professional. Consult a " +
        "licensed advocate before relying on or submitting this document."
  );

  return pdf.build();
}

// ── Helpers ───────────────────────────────────────────────────────────────────

/** Splits on double-newlines to render as separate paragraphs. */
function _addMultiParagraph(pdf, text) {
  if (!text) return;
  const paragraphs = text.split(/\n\n+/);
  for (const p of paragraphs) {
    const trimmed = p.trim();
    if (trimmed) {
      pdf.addParagraph(trimmed);
    }
  }
}

